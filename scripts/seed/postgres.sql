-- -------------------------------------------------------------- order_items
-- Composite primary key, two foreign keys, and a stored generated column.
CREATE TABLE order_items (
    order_id   bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    line_no    smallint NOT NULL,
    sku        varchar(16) NOT NULL REFERENCES products (sku),
    quantity   integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL,
    line_total numeric(12, 2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    PRIMARY KEY (order_id, line_no)
);

INSERT INTO order_items (order_id, line_no, sku, quantity, unit_price)
SELECT o.id, n::smallint, p.sku, 1 + ((o.id + n) % 4), p.price
FROM orders o
CROSS JOIN generate_series(1, 3) AS g (n)
CROSS JOIN LATERAL (
    SELECT sku, price FROM products
    ORDER BY sku
    OFFSET (o.id * 3 + n) % (SELECT count(*) FROM products) LIMIT 1
) p
WHERE (o.id + n) % 3 <> 0;

-- ------------------------------------------------------------------- events
-- No primary key and no unique index, so rows are addressed by ctid — and big
-- enough to page, sort and filter through.
CREATE TABLE events (
    occurred_at timestamptz NOT NULL,
    kind        text NOT NULL,
    customer_id integer REFERENCES customers (id),
    payload     jsonb,
    duration_ms integer
);

INSERT INTO events (occurred_at, kind, customer_id, payload, duration_ms)
SELECT now() - (i || ' minutes')::interval,

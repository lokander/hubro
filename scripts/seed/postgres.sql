-- Applied by seed-postgres.sh; re-running drops and recreates everything it
-- owns, so it is safe to run repeatedly.
--
-- Deliberately covers the things the viewer has special handling for: multiple
-- schemas, views and materialized views, identity/generated columns, composite
-- and text primary keys, a keyless table, foreign keys (single and composite),
-- a partial unique index, enum and array types, NULLs, unicode, oversized
-- cells, and a table big enough to page through.


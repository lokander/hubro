-- --------------------------------------------------------------------- view
CREATE VIEW order_summary AS
SELECT o.id AS order_id,
       c.name AS customer,
       o.status,
       o.placed_at,
       count(i.line_no) AS lines,
       coalesce(sum(i.line_total), 0) AS total
FROM orders o
JOIN customers c ON c.id = o.customer_id
LEFT JOIN order_items i ON i.order_id = o.id
GROUP BY o.id, c.name, o.status, o.placed_at;

-- ------------------------------------------------------- analytics (schema)
CREATE SCHEMA analytics;

CREATE TABLE analytics.daily_sales (
    day     date NOT NULL,
    sku     varchar(16) NOT NULL REFERENCES public.products (sku),
    units   integer NOT NULL,
    revenue numeric(12, 2) NOT NULL,
    PRIMARY KEY (day, sku)
);

INSERT INTO analytics.daily_sales (day, sku, units, revenue)
SELECT d::date, p.sku, u.units, round(u.units * p.price, 2)
FROM generate_series(timestamp '2026-01-01', timestamp '2026-03-31', interval '1 day') AS g (d)
CROSS JOIN products p
CROSS JOIN LATERAL (SELECT (extract(day FROM d)::int * length(p.sku)) % 17 AS units) u
WHERE p.discontinued_at IS NULL;

-- Composite FK into sensor_readings' unique index, to exercise multi-column
-- foreign-key navigation.
CREATE TABLE analytics.sensor_alerts (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site       text NOT NULL,
    sensor     text NOT NULL,
    reading_at timestamp NOT NULL,
    severity   text NOT NULL,
    FOREIGN KEY (site, sensor, reading_at)
        REFERENCES public.sensor_readings (site, sensor, reading_at)
);

INSERT INTO analytics.sensor_alerts (site, sensor, reading_at, severity)
SELECT site, sensor, reading_at,
       CASE WHEN celsius > 24 THEN 'critical' ELSE 'warning' END
FROM sensor_readings
WHERE celsius > 23
ORDER BY reading_at
LIMIT 60;

CREATE MATERIALIZED VIEW analytics.customer_totals AS
SELECT c.id,
       c.name,
       count(DISTINCT o.id) AS orders,
       coalesce(sum(i.line_total), 0) AS lifetime_value
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.id
LEFT JOIN order_items i ON i.order_id = o.id
GROUP BY c.id, c.name;

ANALYZE;

-- ------------------------------------------------------------------- orders
-- Non-overridable identity (read-only in the editor), an enum column, and a
-- partial unique index (at most one pending order per customer) that row
-- identity must not mistake for a usable key.
CREATE TABLE orders (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
    status      order_status NOT NULL DEFAULT 'pending',
    placed_at   timestamptz NOT NULL DEFAULT now(),
    ship_to     text,
    coupon      text
);

CREATE INDEX orders_customer_idx ON orders (customer_id);
CREATE UNIQUE INDEX orders_one_pending_per_customer ON orders (customer_id) WHERE status = 'pending';

INSERT INTO orders (id, customer_id, status, placed_at, ship_to, coupon)
OVERRIDING SYSTEM VALUE
SELECT i,
       1 + (i % 12),
       (ARRAY['paid', 'shipped', 'cancelled', 'refunded']::order_status[])[1 + (i % 4)],
       now() - (i || ' days')::interval,
       CASE WHEN i % 5 = 0 THEN NULL ELSE 'Storgata ' || i || ', Oslo' END,
       CASE WHEN i % 6 = 0 THEN 'SUMMER10' END
FROM generate_series(1, 40) AS g (i);

